def diagram_font(size):
    """Resolve a CJK font without depending on one developer's Windows path."""
    custom = os.environ.get('DESIGN_CJK_FONT')
    if custom:
        return ImageFont.truetype(custom, size)
    candidates = [
        Path(os.environ.get('WINDIR', 'C:/Windows')) / 'Fonts' / 'msyh.ttc',
        Path('/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc'),
        Path('/usr/share/fonts/truetype/noto/NotoSansCJK-Regular.ttc'),
        Path('/System/Library/Fonts/PingFang.ttc'),
    ]
    for candidate in candidates:
        if candidate.is_file():
            return ImageFont.truetype(str(candidate), size)
    raise RuntimeError('No CJK font found. Set DESIGN_CJK_FONT to an installed Chinese TTF/TTC/OTF font.')

