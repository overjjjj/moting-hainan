  const capture=async name=>{
   await page.waitForTimeout(300);
   const frame=page.frames().find(x=>x!==page.mainFrame());
   await frame.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
   const height=await frame.locator('#rental-workflow').evaluate(el=>Math.ceil(el.getBoundingClientRect().bottom));
   await page.waitForFunction(h=>document.querySelector('iframe').getBoundingClientRect().height>=h-1,height);
   await page.waitForTimeout(200);
   assert.ok(await frame.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
   await page.screenshot({path:path.join(out,name),fullPage:true});
  };
  await a.locator('[data-income-total="total"]').waitFor();
  await sum('640.00');
  await a.locator('#wf-income-month').selectOption('all');await sum('1,280.00');
  const inner=page.frames().find(x=>x!==page.mainFrame());
  const oldState=await inner.evaluate(()=>JSON.parse(JSON.stringify(window.openai.widgetState)));
  await a.locator('#wf-income-kind').selectOption('renewal');await sum('0.00');
  assert.match(await a.locator('.ia-empty').innerText(),/暂无收款/);
  await a.locator('#wf-income-kind').selectOption('all');
  await a.locator('[data-page="leases"]').click();
  await a.locator('[data-action="new-contract"]').click();
  await a.locator('#wf-contract-phone').fill('13600001820');
  await a.locator('#wf-contract-rent').fill('300');
  await a.locator('#wf-contract-paid').fill('299.99');
  await a.locator('#wf-contract-paidAt').fill('2026-10-20');
  await a.locator('[data-action="contract-review"]').click();
  assert.match(await a.locator('.ia-modal').innerText(),/2026-10-20/);
  await a.locator('#wf-contract-confirmed').check();
  await a.locator('[data-action="contract-save"]').click();
  await a.getByRole('button',{name:'关闭',exact:true}).click();
  await a.locator('[data-page="income"]').click();
  await a.locator('#wf-income-month').selectOption('2026-10');await sum('939.99');
  await inner.evaluate(state=>window.dispatchEvent(new CustomEvent('openai:set_globals',{detail:{globals:{widgetState:state}}})),oldState);
  await sum('939.99');
  await a.locator('[data-page="leases"]').click();
  await a.locator('[data-renew="01"]').click();
  await a.locator('#wf-renew-paid').fill('360');
  await a.locator('#wf-renew-paidAt').fill('2026-10-21');
  await a.locator('#wf-renew-reference').fill('FK-XZ-20261021');
  await a.locator('#wf-renew-confirmed').check();
  await a.locator('[data-action="renew-save"]').click();
  await a.locator('[data-page="income"]').click();await sum('1,299.99');
  assert.equal(await a.locator('[data-income-sum]').innerText(),'1,299.99');
  await a.locator('#ia-toast').waitFor({state:'hidden'});
  await capture('income-desktop.png');
  await a.locator('#wf-income-kind').selectOption('renewal');await sum('360.00');
